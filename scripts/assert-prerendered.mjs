// Fails the build if any route is rendered per request rather than prerendered.
//
// The whole architecture rests on the public site being static: the CMS is off
// the request path, so the box being asleep only delays publishing instead of
// taking the site down (docs/PLAN.md). A single `cookies()`, `headers()` or
// uncached `fetch()` quietly opts a route out of that, and nothing about the
// deployed page looks different — it just starts costing a function invocation
// and a cold start on every view. This is the check that notices.
//
// Two manifests, read together, are the signal. `routes-manifest.json` lists
// every route the build produced; `prerender-manifest.json` lists only the ones
// it actually rendered ahead of time. A route present in the first and missing
// from the second is server-rendered per request.

import { readFileSync } from "node:fs";

const read = (name) =>
  JSON.parse(readFileSync(new URL(`../apps/web/.next/${name}`, import.meta.url)));

const routes = read("routes-manifest.json");
const prerendered = read("prerender-manifest.json");

// A route with a dynamic segment is prerendered under `dynamicRoutes` when
// generateStaticParams supplied its paths, so both maps count as ahead-of-time.
const ahead = new Set([
  ...Object.keys(prerendered.routes ?? {}),
  ...Object.keys(prerendered.dynamicRoutes ?? {}),
]);

const declared = [...routes.staticRoutes, ...routes.dynamicRoutes].map((r) => r.page);
const perRequest = declared.filter((page) => !ahead.has(page));

if (perRequest.length > 0) {
  console.error(
    `Rendered per request, not prerendered: ${perRequest.join(", ")}\n` +
      "The public site is statically generated by design (docs/PLAN.md). If a\n" +
      "route genuinely has to be dynamic, that is a decision to argue in the\n" +
      "plan first — not a build output to accept quietly.",
  );
  process.exit(1);
}

console.log(`Prerendered: ${declared.join(", ")}`);
